"""Product catalog: loading, search, filtering and faceting.

The dataset is generated by ``app.shop.catalog.generate_catalog`` and committed
as JSON, so the storefront boots with no database and no network. Everything
above this module reads products through the helpers here.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from .categories import CATEGORIES, CATEGORY_ORDER, category_label
from .ml import TfidfIndex, popularity_score, tokenize, trending_score

HERE = Path(__file__).resolve().parent
CATALOG_DIR = HERE / "dataset"
PRODUCTS_FILE = CATALOG_DIR / "products.json"
ORDERS_FILE = CATALOG_DIR / "orders.json"

SORT_OPTIONS = [
    ("relevance", "Best match"),
    ("popular", "Most popular"),
    ("price-asc", "Price: low to high"),
    ("price-desc", "Price: high to low"),
    ("rating", "Highest rated"),
    ("discount", "Biggest discount"),
    ("newest", "Newest arrivals"),
]


class CatalogError(RuntimeError):
    """Raised when the committed catalog is missing or unreadable."""


def _read_json(path: Path):
    if not path.exists():
        raise CatalogError(
            f"Catalog file missing: {path}. "
            "Regenerate it with: python -m app.shop.dataset.generate_catalog"
        )
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:  # pragma: no cover - corrupt file path
        raise CatalogError(f"Catalog file is not valid JSON: {path} ({exc})") from exc


@lru_cache(maxsize=1)
def products() -> tuple[dict, ...]:
    """Every product, as an immutable tuple so callers cannot mutate the cache."""
    return tuple(_read_json(PRODUCTS_FILE))


@lru_cache(maxsize=1)
def orders() -> tuple[dict, ...]:
    """Synthetic order baskets used for collaborative filtering."""
    return tuple(_read_json(ORDERS_FILE))


@lru_cache(maxsize=1)
def product_by_id() -> dict[str, dict]:
    return {p["id"]: p for p in products()}


@lru_cache(maxsize=1)
def product_by_slug() -> dict[str, dict]:
    return {p["slug"]: p for p in products()}


def product_document(product: dict) -> str:
    """The searchable text of a product.

    Title and category are repeated so they dominate the TF-IDF vector, which
    is what a shopper means by relevance: a query for "laptop" should beat a
    blender that merely mentions the word once in its description.
    """
    parts = [
        product.get("title", "") + " " + product.get("title", ""),
        product.get("brand", "") + " " + product.get("brand", ""),
        product.get("category_label", "") + " " + product.get("subcategory", ""),
        " ".join(product.get("tags", []) or []),
        " ".join((product.get("specs") or {}).values()),
        product.get("description", ""),
    ]
    return " ".join(parts)


@lru_cache(maxsize=1)
def index() -> TfidfIndex:
    """TF-IDF index over the whole catalog."""
    return TfidfIndex({p["id"]: product_document(p) for p in products()})


def get_product(slug: str) -> dict | None:
    """Look a product up by slug, falling back to id."""
    return product_by_slug().get(slug) or product_by_id().get(slug)


def related_by_category(product: dict, limit: int = 8) -> list[dict]:
    """Same-brand or same-subcategory products, cheapest-first tiebreak."""
    pool = [
        p for p in products()
        if p["id"] != product["id"]
        and (p["category"] == product["category"] or p["brand"] == product["brand"])
    ]
    pool.sort(key=lambda p: (
        p["category"] != product["category"],
        p["brand"] != product["brand"],
        abs(p["price"] - product["price"]),
    ))
    return pool[:limit]


def categories_with_counts() -> list[dict]:
    """Category metadata plus how many products sit in each, in display order."""
    counts: dict[str, int] = {}
    for p in products():
        counts[p["category"]] = counts.get(p["category"], 0) + 1
    out = []
    for slug in CATEGORY_ORDER:
        meta = CATEGORIES[slug]
        out.append({
            "slug": slug,
            "label": meta["label"],
            "short": meta["short"],
            "blurb": meta["blurb"],
            "hue": meta["hue"],
            "glyph": meta["glyph"],
            "count": counts.get(slug, 0),
        })
    return out


def all_brands() -> list[str]:
    return sorted({p["brand"] for p in products()})


@lru_cache(maxsize=1)
def price_bounds() -> tuple[int, int]:
    prices = [p["price"] for p in products()]
    return (min(prices), max(prices)) if prices else (0, 0)


def flash_products(limit: int = 12) -> list[dict]:
    """Flash-sale items, deepest discount first."""
    pool = [p for p in products() if p.get("flash")]
    pool.sort(key=lambda p: -p["discount_pct"])
    return pool[:limit]


def top_rated(limit: int = 8) -> list[dict]:
    """Highest rated, using the Bayesian prior from ml.bayesian_rating."""
    from .ml import bayesian_rating
    pool = sorted(products(), key=lambda p: -bayesian_rating(p["rating"], p["reviews"]))
    return pool[:limit]


def trending(limit: int = 8) -> list[dict]:
    pool = sorted(
        products(),
        key=lambda p: -trending_score(
            p["sold"], p["reviews"], p["discount_pct"], p["created_days_ago"]
        ),
    )
    return pool[:limit]


def newest(limit: int = 8) -> list[dict]:
    return sorted(products(), key=lambda p: p["created_days_ago"])[:limit]


