# Search and filtering
# --------------------------------------------------------------------------

def _apply_filters(items, category=None, brands=None, min_price=None,
                   max_price=None, min_rating=None, express=None, flash=None,
                   in_stock=None):
    out = []
    for p in items:
        if category and p["category"] != category:
            continue
        if brands and p["brand"] not in brands:
            continue
        if min_price is not None and p["price"] < min_price:
            continue
        if max_price is not None and p["price"] > max_price:
            continue
        if min_rating is not None and p["rating"] < min_rating:
            continue
        if express and not p["express"]:
            continue
        if flash and not p.get("flash"):
            continue
        if in_stock and p["stock"] <= 0:
            continue
        out.append(p)
    return out


def _sort(items, sort: str, scores: dict[str, float]) -> list[dict]:
    if sort == "price-asc":
        return sorted(items, key=lambda p: p["price"])
    if sort == "price-desc":
        return sorted(items, key=lambda p: -p["price"])
    if sort == "rating":
        from .ml import bayesian_rating
        return sorted(items, key=lambda p: -bayesian_rating(p["rating"], p["reviews"]))
    if sort == "discount":
        return sorted(items, key=lambda p: -p["discount_pct"])
    if sort == "newest":
        return sorted(items, key=lambda p: p["created_days_ago"])
    if sort == "popular":
        return sorted(items, key=lambda p: -popularity_score(
            p["sold"], p["reviews"], p["discount_pct"]))
    # relevance
    return sorted(items, key=lambda p: (-scores.get(p["id"], 0.0), -p["sold"]))


def _search_tokens() -> dict[str, set[str]]:
    """Normalised token set per product, over the fields that define relevance.

    Descriptions are excluded: a blender that mentions "phone" once in its
    marketing copy should not match a search for phones.
    """
    out: dict[str, set[str]] = {}
    for p in products():
        text = " ".join([
            p["title"], p["brand"], p["subcategory"], p["category_label"],
            " ".join(p.get("tags", []) or []),
        ])
        out[p["id"]] = set(tokenize(text))
    return out


def query_products(q: str | None = None, category: str | None = None,
                   brands: list[str] | None = None, min_price: int | None = None,
                   max_price: int | None = None, min_rating: float | None = None,
                   express: bool = False, flash: bool = False,
                   sort: str = "relevance", limit: int | None = None,
                   offset: int = 0) -> list[dict]:
    """Filter, score and sort the catalog. Returns plain product dicts."""
    scores: dict[str, float] = {}
    pool = list(products())

    query = (q or "").strip()
    if query:
        idx = index()
        qvec = idx.vectorize(query)
        for p in pool:
            scores[p["id"]] = idx.dot(qvec, idx.vectors.get(p["id"], {}))

        # Exact-word fallback for when TF-IDF is thin. Matching whole tokens
        # (not raw substrings) is what stops a search for "phone" from
        # surfacing "headphones" on a substring hit.
        needle_tokens = set(tokenize(query))
        if needle_tokens:
            token_map = _search_tokens()
            for p in pool:
                if needle_tokens <= token_map.get(p["id"], set()):
                    scores[p["id"]] = max(scores.get(p["id"], 0.0), 0.55)

        if sort == "relevance":
            pool = [p for p in pool if scores.get(p["id"], 0.0) > 0]
    else:
        for p in pool:
            scores[p["id"]] = popularity_score(p["sold"], p["reviews"], p["discount_pct"])

    pool = _apply_filters(
        pool, category=category, brands=brands, min_price=min_price,
        max_price=max_price, min_rating=min_rating, express=express, flash=flash,
    )
    pool = _sort(pool, sort or "relevance", scores)
    if offset:
        pool = pool[offset:]
    if limit is not None:
        pool = pool[:limit]
    return pool


def suggestions(q: str, limit: int = 6) -> list[dict]:
    """Lightweight autocomplete: title/tag substring matches, most popular first."""
    needle = (q or "").strip().lower()
    if len(needle) < 2:
        return []
    hits = []
    for p in products():
        haystack = " ".join([p["title"], p["brand"], p["subcategory"],
                             " ".join(p.get("tags", []) or [])]).lower()
        if needle in haystack:
            hits.append(p)
    hits.sort(key=lambda p: (
        0 if p["title"].lower().startswith(needle) else 1,
        -popularity_score(p["sold"], p["reviews"], p["discount_pct"]),
    ))
    return hits[:limit]


def facets(items: list[dict]) -> dict:
    """Aggregate counts for the filter sidebar, computed over the current result set."""
    brand_counts: dict[str, int] = {}
    cat_counts: dict[str, int] = {}
    for p in items:
        brand_counts[p["brand"]] = brand_counts.get(p["brand"], 0) + 1
        cat_counts[p["category"]] = cat_counts.get(p["category"], 0) + 1
    return {
        "brands": sorted(brand_counts.items(), key=lambda kv: (-kv[1], kv[0])),
        "categories": [
            {"slug": slug, "label": category_label(slug), "count": count}
            for slug, count in sorted(cat_counts.items(), key=lambda kv: -kv[1])
        ],
        "max_price": max((p["price"] for p in items), default=0),
        "min_price": min((p["price"] for p in items), default=0),
    }
